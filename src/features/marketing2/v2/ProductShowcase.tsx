const STEPS = STAGES.flatMap((stage, si) => stage.spots.map((spot, j) => ({ stage, si, spot, j })));
const SPOT_MS = 4600;

const clamp = (v: number, lo: number, hi: number) => Math.min(hi, Math.max(lo, v));

/** Scale and offset (px, origin top-left) that bring `r` to the centre of a W × H viewport showing a 16:10 screenshot. */
function camera(r: Rect, W: number, H: number, boost = 1) {
  if (!W || !H) return { scale: 1, x: 0, y: 0 };
  const narrow = W < 560;
  const rw = (r[2] / 100) * W;
  const rh = (r[3] / 100) * H;
  const fit = Math.min((W * 0.96) / rw, (H * 0.94) / rh);
  const scale = Math.max(1, clamp(fit, 1, narrow ? 2.6 : 1.5) * boost);
  const cx = ((r[0] + r[2] / 2) / 100) * W;
  const cy = ((r[1] + r[3] / 2) / 100) * H;
  return {
    scale,
    x: clamp(W / 2 - cx * scale, W - W * scale, 0),
    y: clamp(H / 2 - cy * scale, H - H * scale, 0),
  };
}

function useSize<T extends HTMLElement>() {
  const ref = useRef<T>(null);
  const [size, setSize] = useState({ w: 0, h: 0 });
  useLayoutEffect(() => {
    const el = ref.current;
    if (!el) return;
    const ro = new ResizeObserver(([e]) => setSize({ w: e.contentRect.width, h: e.contentRect.height }));
    ro.observe(el);
    return () => ro.disconnect();
  }, []);
  return [ref, size] as const;
}

/**
 * Homepage V2 hero: Generate → Train → Analyze → Backtest → Improve → Deploy, shown in one app window with
 * real result pages of the MSFT research chain (Improve uses the DIS1 model). Auto-plays while visible;
 * hover or focus pauses it, choosing a stage stops it, and reduced motion turns it off.
 */
export function ProductShowcase() {
  const reduce = useReducedMotion();
  const [step, setStep] = useState(0);
  const [hold, setHold] = useState(false);
  const [stopped, setStopped] = useState(false);
  const root = useRef<HTMLDivElement>(null);
  const inView = useInView(root, { amount: 0.3 });
  const tabs = useRef<(HTMLButtonElement | null)[]>([]);
  const [view, size] = useSize<HTMLDivElement>();
  const swipe = useRef<number | null>(null);
  const { openShot, lightbox } = useLightbox();
  const uid = useId();
  const auto = !reduce && !stopped && !hold && inView;

  const { stage, si, spot, j } = STEPS[step];
  const narrow = size.w > 0 && size.w < 560;
  const rect = (narrow && spot.mobile) || spot.rect;
  const cam = camera(rect, size.w, size.h);

  useEffect(() => {
    if (!auto) return;
    const id = window.setTimeout(() => setStep((k) => (k + 1) % STEPS.length), SPOT_MS);
    return () => window.clearTimeout(id);
  }, [auto, step]);

  useEffect(() => {
    const tab = tabs.current[si];
    const strip = tab?.parentElement;
    if (!tab || !strip) return;
    const left = tab.offsetLeft - strip.offsetLeft;
    if (left < strip.scrollLeft || left + tab.offsetWidth > strip.scrollLeft + strip.clientWidth)
      strip.scrollTo({ left: left - 8, behavior: reduce ? "auto" : "smooth" });
  }, [si, reduce]);

  useEffect(() => {
    const id = window.setTimeout(() => {
      for (const s of new Set(STEPS.map((x) => x.spot.shot))) new Image().src = screen(s);
    }, 1200);
    return () => window.clearTimeout(id);
  }, []);

  const go = (k: number) => {
    setStopped(true);
    setStep((k + STEPS.length) % STEPS.length);
  };
  const goStage = (i: number, focus = false) => {
    go(STEPS.findIndex((x) => x.si === i));
    if (focus) tabs.current[i]?.focus();
  };

  const onTabKey = (e: KeyboardEvent<HTMLDivElement>) => {
    const last = STAGES.length - 1;
    const next =
      e.key === "ArrowRight" ? (si === last ? 0 : si + 1)
      : e.key === "ArrowLeft" ? (si === 0 ? last : si - 1)
      : e.key === "Home" ? 0
      : e.key === "End" ? last
      : null;
    if (next == null) return;
    e.preventDefault();
    goStage(next, true);
  };

  const onPointerDown = (e: PointerEvent) => {
    if (e.pointerType !== "mouse") swipe.current = e.clientX;
  };
  const onPointerUp = (e: PointerEvent) => {
    if (swipe.current == null) return;
    const dx = e.clientX - swipe.current;
    swipe.current = null;
    if (Math.abs(dx) > 40) go(step + (dx < 0 ? 1 : -1));
    else setStopped(true);
  };

  const enter = reduce ? false : { opacity: 0, ...camera(rect, size.w, size.h, 0.94) };

  return (
    <div
      ref={root}
      onMouseEnter={() => setHold(true)}
      onMouseLeave={() => setHold(false)}
      onFocusCapture={() => setHold(true)}
      onBlurCapture={() => setHold(false)}
    >
      <div className="flex items-center gap-2">
        <div
          role="tablist"
          aria-label="Convolve workflow"
          onKeyDown={onTabKey}
          className="-ml-1 flex min-w-0 flex-1 gap-1 overflow-x-auto pb-px pl-1 [scrollbar-width:none] [&::-webkit-scrollbar]:hidden"
        >
          {STAGES.map((st, i) => {
            const on = i === si;
            return (
              <button
                key={st.id}
                ref={(el) => (tabs.current[i] = el)}
                id={`${uid}-tab-${st.id}`}
                role="tab"
                type="button"
                aria-selected={on}
                aria-controls={`${uid}-panel`}
                tabIndex={on ? 0 : -1}
                onClick={() => goStage(i)}
                className={cn(
                  "relative flex shrink-0 items-baseline gap-2 overflow-hidden rounded-lg px-3 py-2 text-left transition-colors duration-200 focus:outline-none focus-visible:ring-2 focus-visible:ring-[color:var(--convolve-focus-ring)]",
                  on ? "bg-white/[0.07] text-white" : "text-white/45 hover:bg-white/[0.03] hover:text-white/80",
                )}
              >
                <span className={cn("font-mono text-[10.5px] tabular-nums", on ? "text-white/70" : "text-white/30")}>{String(i + 1).padStart(2, "0")}</span>
                <span className="text-[14px] font-medium sm:text-[14.5px]">{st.name}</span>
                {on ? (
                  <motion.span
                    key={`p-${step}-${auto}`}
                    aria-hidden
                    className="absolute inset-x-0 bottom-0 h-px origin-left bg-white/55"
                    initial={{ scaleX: auto ? j / st.spots.length : (j + 1) / st.spots.length }}
                    animate={{ scaleX: (j + 1) / st.spots.length }}
                    transition={{ duration: auto ? SPOT_MS / 1000 : 0, ease: "linear" }}
                  />
                ) : null}
              </button>
            );
          })}
        </div>
        <button
          type="button"
          onClick={() => setStopped((s) => !s)}
          disabled={!!reduce}
          aria-label={stopped || reduce ? "Play the walkthrough" : "Pause the walkthrough"}
          className="grid h-8 w-8 shrink-0 place-items-center rounded-full border border-white/15 text-white/60 transition-colors hover:border-white/35 hover:text-white focus:outline-none focus-visible:ring-2 focus-visible:ring-[color:var(--convolve-focus-ring)] disabled:opacity-0"
        >
          {stopped || reduce ? <Play className="h-3.5 w-3.5" aria-hidden /> : <Pause className="h-3.5 w-3.5" aria-hidden />}
        </button>
      </div>

      <div id={`${uid}-panel`} role="tabpanel" aria-labelledby={`${uid}-tab-${stage.id}`} className="mt-3">
        <figure className="overflow-hidden rounded-[14px] border border-white/[0.1] bg-[#08090b] shadow-[0_40px_120px_-40px_rgba(0,0,0,0.9)]">
          <div className="flex h-9 items-center justify-between gap-3 border-b border-white/[0.07] px-3.5">
            <span className="flex min-w-0 items-center gap-2.5">
              <span className="flex gap-1" aria-hidden>
                <span className="h-2 w-2 rounded-full bg-white/15" />
                <span className="h-2 w-2 rounded-full bg-white/10" />
                <span className="h-2 w-2 rounded-full bg-white/10" />
              </span>
              <span className="min-w-0 truncate font-mono text-[10.5px] text-white/45">
                <span className="text-white/70">convolve</span> / {spot.path}
              </span>
            </span>
            <button
              type="button"
              onClick={() => openShot({ key: spot.shot, file: spot.shot, path: spot.path, alt: spot.alt, notes: [] })}
              className="inline-flex shrink-0 items-center gap-1.5 rounded-md px-1.5 py-0.5 font-mono text-[10px] uppercase tracking-[0.14em] text-white/45 transition-colors hover:text-white focus:outline-none focus-visible:ring-1 focus-visible:ring-white/50"
            >
              <Maximize2 className="h-3 w-3" aria-hidden />
              <span className="hidden sm:inline">Full page</span>
              <span className="sr-only sm:hidden">Open full page</span>
            </button>
          </div>

          <div
            ref={view}
            className="relative aspect-[16/10] touch-pan-y select-none overflow-hidden bg-[#050506]"
            onPointerDown={onPointerDown}
            onPointerUp={onPointerUp}
            onPointerCancel={() => (swipe.current = null)}
          >
            <AnimatePresence initial={false}>
              <motion.div
                key={spot.shot}
                className="absolute left-0 top-0 h-full w-full will-change-transform"
                style={{ transformOrigin: "0 0" }}
                initial={enter}
                animate={{ opacity: 1, ...cam }}
                exit={{ opacity: 0, transition: { duration: reduce ? 0 : 0.5, ease: EASE } }}
                transition={{ duration: reduce ? 0 : 1.15, ease: EASE, opacity: { duration: reduce ? 0 : 0.55 } }}
              >
                <img
                  src={screen(spot.shot)}
                  alt={spot.alt}
                  width={1920}
                  height={1200}
                  decoding="async"
                  fetchPriority={step === 0 ? "high" : undefined}
                  draggable={false}
                  className="absolute inset-0 h-full w-full"
                />
                <motion.div
                  key={`hl-${step}`}
                  aria-hidden
                  className="pointer-events-none absolute rounded-[6px] border-white/60"
                  style={{
                    left: `${rect[0]}%`,
                    top: `${rect[1]}%`,
                    width: `${rect[2]}%`,
                    height: `${rect[3]}%`,
                    borderWidth: 1.25 / cam.scale,
                    boxShadow: "0 0 0 9999px rgba(3,4,6,0.42)",
                  }}
                  initial={reduce ? false : { opacity: 0 }}
                  animate={{ opacity: 1 }}
                  transition={{ duration: reduce ? 0 : 0.6, delay: reduce ? 0 : 0.45, ease: EASE }}
                />
              </motion.div>
            </AnimatePresence>
          </div>

          <figcaption className="grid border-t border-white/[0.07] [grid-template-areas:'c']">
            {STEPS.map((x, k) => (
              <div
                key={k}
                aria-hidden={k !== step}
                className={cn(
                  "flex items-start gap-3 px-4 py-3 transition-opacity duration-300 [grid-area:c] sm:items-center",
                  k === step ? "opacity-100" : "invisible opacity-0",
                )}
              >
                <span className="mt-0.5 shrink-0 font-mono text-[10.5px] uppercase tracking-[0.14em] text-white/45 sm:mt-0">{x.spot.label}</span>
                <span className="min-w-0 text-[13.5px] leading-snug text-white/85">{x.spot.note}</span>
              </div>
            ))}
          </figcaption>
        </figure>

        <div className="mt-3 flex items-center justify-between gap-4">
          <div className="flex shrink-0 items-center gap-1.5" role="group" aria-label={`${stage.name} views`}>
            {stage.spots.map((s, k) => {
              const idx = STEPS.findIndex((x) => x.si === si && x.j === k);
              const on = k === j;
              return (
                <button
                  key={s.label}
                  type="button"
                  aria-pressed={on}
                  onClick={() => go(idx)}
                  className={cn(
                    "whitespace-nowrap rounded-full border px-2.5 py-1 text-[12px] transition-colors focus:outline-none focus-visible:ring-2 focus-visible:ring-[color:var(--convolve-focus-ring)]",
                    on ? "border-white/30 text-white" : "border-white/10 text-white/45 hover:border-white/25 hover:text-white/80",
                  )}
                >
                  {s.label}
                </button>
              );
            })}
          </div>
          <span className="min-w-0 truncate font-mono text-[10px] uppercase tracking-[0.14em] text-white/35">
            <span className="mr-1.5 inline-block h-1.5 w-1.5 rounded-full bg-white/80 align-middle" aria-hidden />
            Real<span className="hidden min-[400px]:inline"> result</span> page
            <span className="hidden normal-case tracking-normal text-white/30 sm:inline"> · {stage.source}</span>
          </span>
        </div>

        <div className="mt-5 grid [grid-template-areas:'s']">
          {STAGES.map((st, i) => (
            <div
              key={st.id}
              aria-hidden={i !== si}
              className={cn("grid gap-4 [grid-area:s] sm:grid-cols-2 sm:gap-8", i === si ? "" : "invisible")}
            >
              <motion.p
                className="text-[15.5px] leading-[1.55] text-white/85"
                initial={false}
                animate={{ opacity: i === si ? 1 : 0, y: i === si || reduce ? 0 : 4 }}
                transition={{ duration: 0.4, ease: EASE }}
              >
                {st.summary}
              </motion.p>
              <motion.div
                className="border-l border-white/[0.1] pl-4"
                initial={false}
                animate={{ opacity: i === si ? 1 : 0, y: i === si || reduce ? 0 : 4 }}
                transition={{ duration: 0.4, ease: EASE, delay: reduce ? 0 : 0.05 }}
              >
                <div className="font-mono text-[10.5px] uppercase tracking-[0.16em] text-white/40">Why it matters</div>
                <p className="mt-1.5 text-[14px] leading-[1.55] text-white/55">{st.why}</p>
                <Link
                  to={st.tool.href}
                  tabIndex={i === si ? undefined : -1}
                  className="group mt-2 inline-flex items-center gap-1.5 text-[13px] text-white/65 transition-colors hover:text-white"
                >
                  Open the {st.tool.label}
                  <ArrowRight className="h-3.5 w-3.5 transition-transform group-hover:translate-x-0.5" aria-hidden />
                </Link>
              </motion.div>
            </div>
          ))}
        </div>
      </div>
      {lightbox}
    </div>
  );
}
