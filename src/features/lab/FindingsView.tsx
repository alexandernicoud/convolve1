import { useEffect, useMemo, useState } from "react";
import { ArrowRight, ChevronDown } from "lucide-react";
import { cx, Panel, surface } from "@/features/review/components/primitives";
import { isFiniteNum, MISSING } from "@/lib/viz/format";
import { SEMANTIC } from "@/lib/viz/tokens";
import { labApi, type Finding } from "./api";
import { Limitations, ResultEmpty, useLab } from "./components";
import { formatMeasurement, groupFindings, MODULE_LABEL, TAB_FOR_KIND } from "./lib";

const STATUS_TEXT: Record<Finding["status"], { label: string; help: string }> = {
  supported: { label: "Supported", help: "The 95% interval for a pre-defined comparison excludes the baseline value." },
  hypothesis: { label: "Hypothesis", help: "Suggestive but not established (e.g. one baseline only, or correlational)." },
  observation: { label: "Observation", help: "A descriptive fact about the sample; no comparison is claimed." },
  inconclusive: { label: "Inconclusive", help: "The interval includes the baseline value, or the data are insufficient." },
};

export default function FindingsView() {
  const { sessionId, session, goTab } = useLab();
  const [data, setData] = useState<{ findings: Finding[]; rules: string } | null>(null);
  const [err, setErr] = useState<string | null>(null);
  const [showRules, setShowRules] = useState(false);
  const succeededKey = useMemo(
    () =>
      session.jobs
        .filter((j) => j.status === "succeeded")
        .map((j) => j.job_id)
        .sort()
        .join(","),
    [session.jobs],
  );

  useEffect(() => {
    if (!sessionId) return;
    let alive = true;
    labApi
      .findings(sessionId)
      .then((d) => alive && (setData(d), setErr(null)))
      .catch((e) => alive && setErr(e instanceof Error ? e.message : "Could not load findings"));
    return () => {
      alive = false;
    };
  }, [sessionId, succeededKey]);

  if (!sessionId) return <ResultEmpty>Findings are derived from completed experiments. Run an atlas, masking, faithfulness, feature or projection experiment first.</ResultEmpty>;
  if (err) return <ResultEmpty>{err}</ResultEmpty>;
  if (!data) return <div className={cx(surface, "h-40 animate-pulse")} />;
  if (!data.findings.length) return <ResultEmpty>No completed experiments in this session yet.</ResultEmpty>;
  const groups = groupFindings(data.findings);

  return (
    <div className="space-y-5">
      <Panel
        title="Research findings"
        description="Generated by fixed rules from the latest result of each experiment in this session. Nothing here is written by hand or by a language model; rerunning with the same results gives the same findings."
        aside={
          <button type="button" onClick={() => setShowRules((s) => !s)} className="inline-flex items-center gap-1 text-[13px] text-white/55 hover:text-white">
            Rules <ChevronDown className={cx("h-4 w-4 transition", showRules && "rotate-180")} />
          </button>
        }
      >
        {showRules ? <pre className="whitespace-pre-wrap rounded-lg border border-white/[0.08] p-3 font-sans text-[12.5px] leading-relaxed text-white/55">{data.rules}</pre> : null}
        <div className="flex flex-wrap gap-x-6 gap-y-1 text-[13px] text-white/55">
          {groups.map((g) => (
            <span key={g.status} className="flex items-center gap-2">
              <StatusGlyph status={g.status} /> {STATUS_TEXT[g.status].label} <span className="font-digits text-white/80">{g.items.length}</span>
            </span>
          ))}
        </div>
      </Panel>
      {groups.map((g) => (
        <section key={g.status} className="space-y-3">
          <h3 className="flex items-center gap-2 pl-1 text-[13px] font-medium text-white/60" title={STATUS_TEXT[g.status].help}>
            <StatusGlyph status={g.status} /> {STATUS_TEXT[g.status].label}
          </h3>
          <div className="grid gap-4 lg:grid-cols-2">
            {g.items.map((f) => (
              <FindingCard key={f.id} f={f} onOpen={() => goTab(TAB_FOR_KIND[f.module])} />
            ))}
          </div>
        </section>
      ))}
    </div>
  );
}

function StatusGlyph({ status }: { status: Finding["status"] }) {
  if (status === "supported") return <span className="h-2 w-2 rounded-full bg-white" />;
  if (status === "hypothesis") return <span className="h-2 w-2 rounded-full border border-dashed border-white/80" />;
  if (status === "observation") return <span className="h-2 w-2 rounded-full bg-white/40" />;
  return <span className="h-2 w-2 rounded-full border border-white/35" />;
}

function FindingCard({ f, onOpen }: { f: Finding; onOpen: () => void }) {
  const m = f.measurement;
  return (
    <article className={cx(surface, "flex flex-col gap-3 px-5 py-4")}>
      <header className="flex items-start justify-between gap-3">
        <h4 className="text-[15px] font-medium leading-snug text-white">{f.title}</h4>
        <span className="shrink-0 rounded-md border border-white/[0.12] px-1.5 py-0.5 text-[11.5px] text-white/60" title={STATUS_TEXT[f.status].help}>
          {STATUS_TEXT[f.status].label}
        </span>
      </header>
      <p className="text-[13.5px] leading-relaxed text-white/70">{f.observation}</p>
      {m ? (
        <div className="rounded-lg border border-white/[0.07] px-3 py-2">
          <p className="text-[12px] text-white/45">{m.label}</p>
          <p className="mt-0.5 font-digits text-[17px] tabular-nums text-white">
            {formatMeasurement(m, m.value)}
            {isFiniteNum(m.lo) && isFiniteNum(m.hi) ? (
              <span className="ml-2 text-[13px] text-white/45">
                [{formatMeasurement(m, m.lo)}, {formatMeasurement(m, m.hi)}]
              </span>
            ) : null}
          </p>
          {isFiniteNum(m.lo) && isFiniteNum(m.hi) && isFiniteNum(m.value) ? <MiniInterval lo={m.lo} hi={m.hi} v={m.value} zeroRef={/−|minus|difference|Δ|Cohen/i.test(m.label)} /> : null}
        </div>
      ) : null}
      <dl className="grid grid-cols-[auto_1fr] gap-x-4 gap-y-1 text-[12.5px]">
        <dt className="text-white/40">n</dt>
        <dd className="font-digits tabular-nums text-white/70">{f.n ?? MISSING}</dd>
        <dt className="text-white/40">Baseline</dt>
        <dd className="text-white/65">{f.baseline ?? "None (descriptive)"}</dd>
      </dl>
      <Limitations items={f.limitations} />
      <button type="button" onClick={onOpen} className="mt-auto inline-flex items-center gap-1 self-start text-[13px] text-white/55 transition hover:text-white">
        Open in {MODULE_LABEL[f.module]} <ArrowRight className="h-3.5 w-3.5" />
      </button>
    </article>
  );
}

/** Interval on its own scale, with a zero tick when the measure is a difference. */
function MiniInterval({ lo, hi, v, zeroRef }: { lo: number; hi: number; v: number; zeroRef: boolean }) {
  const a = Math.min(lo, zeroRef ? 0 : lo);
  const b = Math.max(hi, zeroRef ? 0 : hi);
  const pad = (b - a) * 0.1 || 0.01;
  const x = (t: number) => ((t - (a - pad)) / (b - a + 2 * pad)) * 100;
  return (
    <svg viewBox="0 0 100 10" preserveAspectRatio="none" className="mt-2 h-2.5 w-full" aria-hidden>
      {zeroRef ? <line x1={x(0)} x2={x(0)} y1={0} y2={10} stroke="rgba(255,255,255,0.35)" strokeDasharray="1.5 1.5" vectorEffect="non-scaling-stroke" /> : null}
      <line x1={x(lo)} x2={x(hi)} y1={5} y2={5} stroke="rgba(255,255,255,0.55)" strokeWidth={2} vectorEffect="non-scaling-stroke" />
      <line x1={x(v)} x2={x(v)} y1={1} y2={9} stroke={SEMANTIC.highlight} strokeWidth={3} vectorEffect="non-scaling-stroke" />
    </svg>
  );
}
